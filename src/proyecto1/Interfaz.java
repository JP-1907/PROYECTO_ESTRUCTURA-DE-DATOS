 /**
 *Botón: "Detectar" (BFS).
  
     *Ejecuta BFS sobre el grafo para encontrar componentes conexos (complejos proteicos).
     * Un “complejo” aquí significa: conjunto de proteínas que están conectadas entre sí por alguna ruta.
     * Imprime cada complejo con: número de complejo, tamaño y lista de IDs.
 * @param evt 
 */   
    private void BFSActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BFSActionPerformed
        MostrarAnalisis.append("\n");
        MostrarAnalisis.append("Iniciando escaneo de complejos (BFS)...\n");

        try {
            AnalisisGrafo analizador = new AnalisisGrafo(miGrafo);
            Lista<Lista<Proteina>> BFS = analizador.encontrarConexas(); 
            int totalComplejos = BFS.getSize();
            int numComplejo = 1; 
            Nodo<Lista<Proteina>> nodoComplejo = BFS.getInicio();
    
            while (nodoComplejo != null) {
                Lista<Proteina> complejoActual = nodoComplejo.getDato();
       
                StringBuilder nombresProteinas = new StringBuilder(); /**Arma string con todas las prpteinas de la isla complejo*/
                Nodo<Proteina> proteina = complejoActual.getInicio();
        
                while (proteina != null) {
                    nombresProteinas.append(proteina.getDato().getID());
                    if (proteina.getNext() != null) {
                        nombresProteinas.append(", "); 
                    }
            proteina = proteina.getNext();
                }
        MostrarAnalisis.append("Complejo " + numComplejo + " (" + complejoActual.getSize() + " proteínas): [" + nombresProteinas.toString() + "]\n");
        nodoComplejo = nodoComplejo.getNext();
        numComplejo++;
        }
    
        MostrarAnalisis.append("Se detectaron " + totalComplejos + " complejos proteicos.\n");
            

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al ejecutar BFS: " + e.getMessage(), "Error de Análisis", JOptionPane.ERROR_MESSAGE);
        }

        MostrarAnalisis.append("\n");
                
    }//GEN-LAST:event_BFSActionPerformed
 /**
     * Botón: "Ver Red" (Visualizar).
     *
     *Crea un grafo visual usando GraphStream.
     * Agrega nodos para cada proteína con su ID.
     * 
     *Agrega aristas evitando duplicados usando la regla
     * Muestra la ventana con {@code graphVisual.display()}.
     * 
     */
    private void MostrarRedActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_MostrarRedActionPerformed
        System.setProperty("org.graphstream.ui", "swing");
        try{
            MostrarAnalisis.append("Generando visualización 2D de la red...\n");
            org.graphstream.graph.Graph graphVisual = new org.graphstream.graph.implementations.SingleGraph("Interactoma");
            graphVisual.setAttribute("ui.stylesheet", "node { fill-color: #3498db; size: 20px; text-size: 14px; text-color: black; } edge { fill-color: #7f8c8d; }");
            graphVisual.setAttribute("ui.antialias");
            Nodo<Proteina> auxProt = miGrafo.getListaProteinas().getInicio();
            while (auxProt != null) {
                Proteina p = auxProt.getDato();
                org.graphstream.graph.Node n = graphVisual.addNode(p.getID());
                n.setAttribute("ui.label", p.getID()); 
                auxProt = auxProt.getNext();
            }
            auxProt = miGrafo.getListaProteinas().getInicio();
            while (auxProt != null) {
                Proteina p = auxProt.getDato();
                String idA = p.getID();
                Nodo<Interaccion> auxInt = p.getAdyacentes().getInicio();
                while (auxInt != null) {
                    Interaccion inter = auxInt.getDato();
                    String idB = inter.getPB().getID();

                    if (idA.compareTo(idB) < 0) {
                        String idArista = idA + "-" + idB; 
                        graphVisual.addEdge(idArista, idA, idB);
                    }
                    auxInt = auxInt.getNext();
                    }
                    auxProt = auxProt.getNext();
                }
            graphVisual.display();
            
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error de visualización: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        } 
    }//GEN-LAST:event_MostrarRedActionPerformed
