/**    * Botón: "Calcular" (Dijkstra).
     *  Lee proteína origen y destino desde ComboBox.
     *   Ejecuta {@link AnalisisGrafo#rutaMasCorta(String, String)} usando Dijkstra.
     *   Si hay ruta, imprime:La secuencia de proteínas: A -> ... -> B
     *   La resistencia total acumulada (distancia) almacenada en el nodo final.
     */
    private void CalcularDijkstraActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_CalcularDijkstraActionPerformed
        if (PADijkstra.getSelectedItem() == null || PBDijkstra.getSelectedItem() == null) {
        JOptionPane.showMessageDialog(this, "Seleccione proteína de origen y destino.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        String origen = PADijkstra.getSelectedItem().toString();
        String destino = PBDijkstra.getSelectedItem().toString();
        if (origen.equals(destino)) {
            JOptionPane.showMessageDialog(this,
                "Seleccione proteínas distintas para calcular una ruta.",
                "Selección inválida",
                JOptionPane.WARNING_MESSAGE);
            return;
        }

        MostrarAnalisis.append("\n");
        MostrarAnalisis.append("Calculando ruta metabólica de " + origen + " a " + destino + "...\n");

        try {
            AnalisisGrafo analizador = new AnalisisGrafo(miGrafo);
            Lista<Proteina> ruta = analizador.rutaMasCorta(origen, destino);

            if (ruta == null) {
                MostrarAnalisis.append("No existe conexión entre " + origen + " y " + destino + ".\n");
            } else {
                StringBuilder rutaStr = new StringBuilder();
                Nodo<Proteina> actual = ruta.getInicio();
                double pesoTotal = 0.0;
                while (actual != null) {
                    Proteina p = actual.getDato();
                    rutaStr.append(p.getID());

                    if (actual.getNext() != null) {
                        rutaStr.append(" -> ");
                    } else {
                        pesoTotal = p.getDist(); 
                    }
                    actual = actual.getNext();
                }

                MostrarAnalisis.append("RUTA: " + rutaStr.toString() + "\n");
                MostrarAnalisis.append("RESISTENCIA TOTAL: " + pesoTotal + "\n");
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error en Dijkstra: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
        MostrarAnalisis.append(" \n");
    }//GEN-LAST:event_CalcularDijkstraActionPerformed
